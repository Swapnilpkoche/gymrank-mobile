-- A voter is eligible for a city-level matchup if they have a verified
-- check-in at ANY gym whose primary location resolves to this contest's
-- city - same gym_locations -> localities -> cities join used by
-- search_gyms.
create or replace function public.enforce_bracket_vote_rules()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_matchup public.bracket_matchups%rowtype;
  v_round public.bracket_rounds%rowtype;
  v_contest public.contest_periods%rowtype;
  v_has_valid_checkin boolean;
begin
  select * into v_matchup from public.bracket_matchups where id = new.matchup_id;
  if v_matchup is null then
    raise exception 'Matchup not found.';
  end if;

  if v_matchup.status <> 'voting' then
    raise exception 'Voting is not currently open for this matchup.';
  end if;

  if new.nominee_id <> v_matchup.nominee_a_id and new.nominee_id <> v_matchup.nominee_b_id then
    raise exception 'This nominee is not part of this matchup.';
  end if;

  select * into v_round from public.bracket_rounds where id = v_matchup.round_id;
  select * into v_contest from public.contest_periods where id = v_round.contest_period_id;

  select exists (
    select 1
    from public.gym_checkins c
    join public.gym_locations gl on gl.gym_id = c.gym_id and gl.is_primary = true
    join public.localities loc on loc.id = gl.locality_id
    join public.cities ci on ci.id = loc.city_id
    where c.user_id = new.voter_id
      and c.is_valid = true
      and ci.id = v_contest.city_id
  ) into v_has_valid_checkin;

  if not v_has_valid_checkin then
    raise exception 'You need a verified check-in at a gym in this city to vote in this contest.';
  end if;

  return new;
end;
$function$;

create trigger trg_enforce_bracket_vote_rules
  before insert on public.bracket_votes
  for each row
  execute function public.enforce_bracket_vote_rules();

-- Secret ballot, same as gym-level votes: a voter sees only their own vote.
create policy "Voter can view their own bracket vote"
on public.bracket_votes for select
using (voter_id = auth.uid());

create policy "Users can cast their own bracket vote"
on public.bracket_votes for insert
with check (voter_id = auth.uid());

grant select, insert on public.bracket_votes to authenticated;
