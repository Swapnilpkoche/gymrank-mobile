-- bracket_rounds
-- ============================================================
create table public.bracket_rounds (
  id bigint generated by default as identity primary key,
  contest_period_id bigint not null references public.contest_periods(id),
  round_number integer not null,
  voting_start timestamptz not null,
  voting_end timestamptz not null,
  status text not null default 'pending' check (status in ('pending', 'voting', 'completed')),
  created_at timestamptz not null default now(),
  unique (contest_period_id, round_number)
);

alter table public.bracket_rounds enable row level security;

create or replace function public.enforce_bracket_round_is_city_level()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  if not exists (
    select 1 from public.contest_periods cp
    where cp.id = new.contest_period_id and cp.level = 'city'
  ) then
    raise exception 'Bracket rounds can only belong to a city-level contest period.';
  end if;
  return new;
end;
$function$;

create trigger trg_enforce_bracket_round_is_city_level
  before insert on public.bracket_rounds
  for each row
  execute function public.enforce_bracket_round_is_city_level();

create policy "Anyone can view bracket rounds"
on public.bracket_rounds for select using (true);

grant select on public.bracket_rounds to anon, authenticated;

